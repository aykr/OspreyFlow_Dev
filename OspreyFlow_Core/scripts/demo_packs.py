def _build(manifest: DemoManifest) -> DemoPack:
    description = _DESCRIPTIONS.get(manifest.id)
    if description is None:
        raise RuntimeError(
            f"The shipped demo '{manifest.id}' has no pack description in scripts/demo_packs.py."
        )
    if manifest.delivery == DELIVERY_DOWNLOAD and description.download is None:
        raise RuntimeError(f"The download pack '{manifest.id}' has no download details.")
    return DemoPack(
        id=manifest.id,
        title=description.title,
        shows=description.shows,
        delivery=manifest.delivery,
        seed_module=manifest.seed_module,
        licence=manifest.data_licence or _OWNED,
        attribution=manifest.attribution,
        download=description.download if manifest.delivery == DELIVERY_DOWNLOAD else None,
        case_name=description.case_name,
        real_data=description.real_data,
    )


def packs(registry: tuple[DemoManifest, ...] = REGISTRY) -> tuple[DemoPack, ...]:
    """One pack per shipped manifest, in registry order."""
    return tuple(_build(m) for m in registry if m.is_shipped)


def pack(pack_id: str, registry: tuple[DemoManifest, ...] = REGISTRY) -> DemoPack:
    """The named pack. An unknown id and an internal demo are refused in the same words, so the
    refusal never confirms that an internal demo exists."""
    available = packs(registry)
    for candidate in available:
        if candidate.id == pack_id:
            return candidate
    names = ", ".join(p.id for p in available)
    raise PackRefused(f"There is no demo pack called '{pack_id}'. The packs are: {names}.")


def verify_download(path: Path, pack: DemoPack) -> None:
    """Refuse a file that is not exactly the one the pack names; return quietly if it is."""
    if pack.download is None or pack.delivery != DELIVERY_DOWNLOAD:
        raise PackRefused(
            f"The pack '{pack.id}' is seeded from code in this repository; it has nothing to "
            "download."
        )
    expected = pack.download
    if not path.is_file():
        raise PackRefused(
            f"There is no file at {path}. Download {expected.filename} from "
            f"{expected.source_page} and try again."
        )
    actual_size = path.stat().st_size
    if actual_size != expected.size_bytes:
        raise PackRefused(
            f"The file {path.name} is {actual_size:,} bytes, but the pack '{pack.id}' expects "
            f"{expected.size_bytes:,} bytes. It may be incomplete; it should be downloaded again "
            f"from {expected.source_page}."
        )
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(_CHUNK):
            digest.update(chunk)
    if digest.hexdigest() != expected.sha256:
        raise PackRefused(
            f"The SHA-256 checksum of {path.name} does not match the one the pack '{pack.id}' "
            f"expects, so the file is not the original. It should be downloaded again from "
            f"{expected.source_page}."
        )


def _verify(pack_id: str, file: str) -> int:
    """Exit 0 when the file is the pack's own, else print why not and exit 1."""
    try:
        verify_download(Path(file), pack(pack_id))
    except PackRefused as refusal:
        print(refusal, file=sys.stderr)
        return 1
    print(f"{file} is the file the pack '{pack_id}' expects.")
    return 0


def main(argv: list[str] | None = None) -> int:
    """`demo_packs` lists the packs; `--ids` prints only their ids, one per line (what the
    `ospreyflow` command reads); `verify PACK FILE` checks a downloaded file."""
    args = list(sys.argv[1:] if argv is None else argv)
    if args == ["--ids"]:
        for item in packs():
            print(item.id)
        return 0
    if args and args[0] == "verify":
        if len(args) != 3:
            print("usage: demo_packs verify PACK FILE", file=sys.stderr)
            return 2
        return _verify(args[1], args[2])
    if args:
        print("usage: demo_packs [--ids | verify PACK FILE]", file=sys.stderr)
        return 2
    for item in packs():
        size = f"{item.download.size_bytes:,} bytes" if item.download else "generated"
        print(f"{item.id}: {item.title}")
        print(f"  shows: {item.shows}")
        print(f"  delivery: {item.delivery}; size: {size}; licence: {item.licence}")
        if item.real_data:
            print("  REAL personal data: never added by an install; `ospreyflow demo add "
                  f"{item.id} --file <file>` shows what it is and asks first")
        if item.attribution:
            print(f"  attribution: {item.attribution}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
