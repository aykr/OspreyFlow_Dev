// The Runs tab's part in external orchestration (`06_DECISIONS.md` ADR-141 decisions 6, 9 and 11;
// the redesign's phase 10 steps 2, 3 and 5): a deployed pipeline's quota as a bar (today's runs
// into its dataset against the dataset's quota), *Owned externally* (the one service identity an
// orchestrator triggers it as; the person marking it is who each external run acts as), and the
// Airflow DAG generated for it, which runs `ospreyflow run` with the orchestrator's own run id, so
// the map-to-graph and the load stay inside OspreyFlow (R11).
import { useEffect, useState } from "react";

import type { ExternallyOwnedInput, RunQuotaUse, StudioRecipeDraft } from "../../../../../packages/schemas/generated";
import { Button, Input, Select } from "../../design/primitives";

export interface ExternalOrchestrationProps {
  apiBaseUrl: string;
  bearerToken: string;
  investigationId: string;
  datasetId: string | null;
  deployed: readonly StudioRecipeDraft[];
  /** Holds `schedule_pipelines`: may hand a pipeline's schedule to an orchestrator. */
  canSchedule: boolean;
}

export const ORCHESTRATION_WORDS = {
  intro:
    "An orchestrator such as Airflow may trigger a deployed pipeline through OspreyFlow's run API. It signs in as a service identity, and each run acts as the person who marks the pipeline owned externally.",
  noRight: "Handing a pipeline to an orchestrator needs Schedule pipelines.",
  hasSchedule: "This pipeline has a schedule of its own: clear it first, so nobody sets both.",
  noQuota: "No quota of runs a day is set for this dataset.",
} as const;

function recipeUrl(apiBaseUrl: string, investigationId: string, recipeId: string): string {
  return `${apiBaseUrl}/v1/investigations/${encodeURIComponent(investigationId)}/ingest/recipes/${encodeURIComponent(recipeId)}`;
}

async function words(response: Response, what: string): Promise<string> {
  const body = (await response.json().catch(() => ({}))) as { detail?: unknown };
  return typeof body.detail === "string" ? body.detail : `${what} was refused (${response.status}).`;
}

/** The DAG an orchestrator runs: one task, the CLI's `run`, keyed by Airflow's own run id. A pinned
 * version is refused by the Conduit once a newer one is deployed; "latest" runs the deployed one. */
export function airflowDag(datasetId: string, pipeline: StudioRecipeDraft, version: "latest" | number): string {
  const dagId = `ospreyflow_${pipeline.recipe_id.replace(/[^A-Za-z0-9_]/g, "_")}`;
  return [
    // The label is the only free text here: one line, so it can never end the comment it is in.
    `# Generated by OspreyFlow's Studio › Runs for "${pipeline.label.replace(/[\r\n\u2028\u2029]+/g, " ")}" (ADR-141 decision 9).`,
    "# The service identity signs in with OSPREY_TOKEN_URL, OSPREY_CLIENT_ID and OSPREY_CLIENT_SECRET,",
    "# set in the Airflow worker's environment; no secret is written here.",
    "from airflow import DAG",
    "from airflow.operators.bash import BashOperator",
    "import pendulum",
    "",
    `with DAG(dag_id="${dagId}", schedule=None, start_date=pendulum.datetime(2026, 1, 1, tz="Europe/London"), catchup=False) as dag:`,
    "    BashOperator(",
    `        task_id="run",`,
    `        bash_command="ospreyflow run ${datasetId} ${pipeline.recipe_id} --version ${version} --external-run-id {{ dag.dag_id }}:{{ run_id }} --wait --fail-on held",`,
    "    )",
    "",
  ].join("\n");
}

export function ExternalOrchestration(props: ExternalOrchestrationProps) {
  const { apiBaseUrl, bearerToken, investigationId, datasetId, deployed, canSchedule } = props;
  const [chosen, setChosen] = useState(deployed[0]?.recipe_id ?? "");
  const [quota, setQuota] = useState<RunQuotaUse | null>(null);
  const [owned, setOwned] = useState<ExternallyOwnedInput | null>(null);
  const [client, setClient] = useState("");
  const [pin, setPin] = useState<"latest" | "this">("latest");
  const [problem, setProblem] = useState<string | null>(null);
  const [said, setSaid] = useState<string | null>(null);
  const pipeline = deployed.find((p) => p.recipe_id === chosen) ?? deployed[0];
  const headers = { Authorization: `Bearer ${bearerToken}` };

  useEffect(() => {
    if (!pipeline) return;
    let gone = false;
    const url = recipeUrl(apiBaseUrl, investigationId, pipeline.recipe_id);
    fetch(`${url}/quota`, { headers: { Authorization: `Bearer ${bearerToken}` } })
      .then((r) => (r.ok ? (r.json() as Promise<RunQuotaUse>) : null))
      .then((q) => !gone && setQuota(q))
      .catch(() => !gone && setQuota(null));
    if (canSchedule)
      fetch(`${url}/owned-externally`, { headers: { Authorization: `Bearer ${bearerToken}` } })
        .then((r) => (r.ok ? (r.json() as Promise<ExternallyOwnedInput | null>) : null))
        .then((o) => !gone && setOwned(o))
        .catch(() => !gone && setOwned(null));
    return () => {
      gone = true;
    };
  }, [apiBaseUrl, bearerToken, investigationId, pipeline, canSchedule]);

  if (!pipeline || !datasetId) return null;
  const url = recipeUrl(apiBaseUrl, investigationId, pipeline.recipe_id);
  const limit = quota?.quota?.runs_per_day ?? null;

  const mark = () => {
    setProblem(null);
    setSaid(null);
    fetch(`${url}/owned-externally`, {
      method: "PUT",
      headers: { ...headers, "Content-Type": "application/json" },
      body: JSON.stringify({ client_id: client.trim() }),
    })
      .then(async (r) => {
        if (!r.ok) throw new Error(await words(r, "Marking it owned externally"));
        setOwned((await r.json()) as ExternallyOwnedInput);
        setSaid(`${pipeline.label} is owned externally: only ${client.trim()} may trigger it, and each run acts as you.`);
      })
      .catch((e: Error) => setProblem(e.message));
  };

  const clear = () => {
    setProblem(null);
    setSaid(null);
    fetch(`${url}/owned-externally`, { method: "DELETE", headers })
      .then(async (r) => {
        if (!r.ok) throw new Error(await words(r, "Taking it back"));
        setOwned(null);
        setSaid(`${pipeline.label} is no longer owned externally.`);
      })
      .catch((e: Error) => setProblem(e.message));
  };

  const dag = airflowDag(datasetId, pipeline, pin === "latest" ? "latest" : pipeline.version);
  const download = () => {
    const link = document.createElement("a");
    link.href = URL.createObjectURL(new Blob([dag], { type: "text/x-python" }));
    link.download = `ospreyflow_${pipeline.recipe_id}.py`;
    link.click();
    URL.revokeObjectURL(link.href);
  };

  return (
    <section aria-label="External orchestration" style={{ display: "grid", gap: "var(--sp-8)" }}>
      <h3 style={{ margin: 0, fontSize: "var(--fs-14)" }}>External orchestration and quota</h3>
      <p className="caption" style={{ margin: 0 }}>
        {ORCHESTRATION_WORDS.intro}
      </p>
      <label style={{ display: "grid", gap: "var(--sp-4)", maxWidth: 360 }}>
        <span>Pipeline</span>
        <Select value={pipeline.recipe_id} onChange={(e) => setChosen(e.target.value)} aria-label="Pipeline to orchestrate">
          {deployed.map((p) => (
            <option key={p.recipe_id} value={p.recipe_id}>
              {p.label}
            </option>
          ))}
        </Select>
      </label>
      <div aria-label="The dataset's quota today">
        {quota && limit !== null ? (
          <>
            <meter
              aria-label="Runs today against the dataset's quota"
              min={0}
              max={limit}
              value={Math.min(quota.runs_today, limit)}
              style={{ width: 240 }}
            />{" "}
            <span>{`${quota.runs_today} of ${limit} runs a day`}</span>
          </>
        ) : (
          <span className="caption">{quota ? ORCHESTRATION_WORDS.noQuota : ""}</span>
        )}
      </div>
      {!canSchedule && (
        <p className="caption" style={{ margin: 0 }}>
          {ORCHESTRATION_WORDS.noRight}
        </p>
      )}
      {canSchedule && owned && (
        <div style={{ display: "flex", gap: "var(--sp-8)", alignItems: "center" }}>
          <span>{`Owned externally: only ${owned.client_id} may trigger it.`}</span>
          <Button onClick={clear}>Take it back</Button>
        </div>
      )}
      {canSchedule && !owned && (
        <div style={{ display: "flex", gap: "var(--sp-8)", alignItems: "end", flexWrap: "wrap" }}>
          <label style={{ display: "grid", gap: "var(--sp-4)" }}>
            <span>The orchestrator's client</span>
            <Input value={client} onChange={(e) => setClient(e.target.value)} />
          </label>
          <Button onClick={mark} disabled={!client.trim() || !!(pipeline.schedule_cron || pipeline.schedule_watch)}>
            Mark owned externally
          </Button>
          {(pipeline.schedule_cron || pipeline.schedule_watch) && <span className="caption">{ORCHESTRATION_WORDS.hasSchedule}</span>}
        </div>
      )}
      <div style={{ display: "flex", gap: "var(--sp-8)", alignItems: "end" }}>
        <label style={{ display: "grid", gap: "var(--sp-4)" }}>
          <span>The DAG runs</span>
          <Select value={pin} onChange={(e) => setPin(e.target.value as "latest" | "this")}>
            <option value="latest">the latest deployed version</option>
            <option value="this">{`version ${pipeline.version} only`}</option>
          </Select>
        </label>
        <Button onClick={download}>Download the Airflow DAG</Button>
      </div>
      <pre aria-label="The Airflow DAG" className="caption" style={{ margin: 0, whiteSpace: "pre-wrap" }}>
        {dag}
      </pre>
      {problem && <p role="alert">{problem}</p>}
      {said && <p role="status">{said}</p>}
    </section>
  );
}
