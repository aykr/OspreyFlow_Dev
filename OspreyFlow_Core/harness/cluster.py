def _environment(config: OspreyConfig) -> dict[str, str]:
    """Lite's `deployment.env`, as the cluster's ConfigMap, with what a cluster adds."""
    from harness.render import _render_env

    environment: dict[str, str] = {}
    for line in _render_env(config).splitlines():
        if line and not line.startswith("#") and "=" in line:
            name, _, value = line.partition("=")
            environment[name] = value
    valkey = config.external.valkey
    assert valkey is not None
    environment.update(
        {
            # Written by `apply` into Lite's env file; the addresses are not secrets.
            "ARCADEDB_HOST": "arcadedb",
            # ADR-101 Amendment 2: written through the Raft leader.
            "ARCADEDB_HA": "true",
            # ADR-114 Amendment 12: a Replicated database, ReplicatedMergeTree tables.
            "CLICKHOUSE_CLUSTER": CLICKHOUSE_CLUSTER,
            "VALKEY_HOST": valkey.host,
            "VALKEY_PORT": str(valkey.port),
            "VALKEY_TLS": "true" if valkey.tls else "false",
        }
    )
    for port_variable in ("OSPREY_API_PORT", "OSPREY_ARCADEDB_PORT"):
        # Published ports are Lite's; a cluster's one door is the proxy's load balancer.
        environment.pop(port_variable, None)
    return environment


def _refuse_what_a_cluster_cannot_run(config: OspreyConfig) -> None:
    if config.components.analytics_engine is not AnalyticsEngine.CLICKHOUSE:
        raise ClusterNotRenderable(
            "a cluster's Conduits share ClickHouse (ADR-114 decision 9); "
            "components.analytics_engine is "
            f"{config.components.analytics_engine.value!r} — DuckDB would give each replica "
            "its own events"
        )
    if config.components.graph_store is not GraphStore.ARCADEDB:
        raise ClusterNotRenderable(
            "a cluster runs ArcadeDB's Raft replicas (ADR-114 decision 9); components.graph_store "
            f"is {config.components.graph_store.value!r}"
        )
    if config.components.source_path is not None:
        raise ClusterNotRenderable(
            "a cluster pulls the release's images; components.source_path asks to build them here"
        )


def render_cluster(
    config: OspreyConfig,
    images: Sequence[ServiceImage],
    *,
    resolver: DigestResolver,
    allow_unpinned: bool,
    resolved_source_label: str,
) -> dict[str, str]:
    """`values.yaml` for the chart, and the `versions.lock` of every image it runs."""
    from harness.render import (
        UnpinnedImagesError,
        _render_versions_lock,
        compose_services,
        render_litellm_config,
    )
    from harness.site import render_caddyfile, render_glass_settings

    _refuse_what_a_cluster_cannot_run(config)
    services = compose_services(config, images)
    environment = _environment(config)
    translate = _Translator(environment)
    theme = render_login_theme(read_tokens(), reset_by_email=config.mail is not None)
    files: dict[str, str] = {
        "Caddyfile": render_caddyfile(config, doors=False),
        "glass.json": render_glass_settings(config),
        "osprey.yaml": yaml.safe_dump(
            config.model_dump(mode="json", exclude_none=True), sort_keys=False
        ),
        "litellm.yaml": render_litellm_config(config),
        "realm.json": render_realm_json(config, demo_analyst=False),
        "clickhouse.xml": clickhouse_config(REPLICAS["clickhouse"], REPLICAS["clickhouse-keeper"]),
        "clickhouse-users.xml": CLICKHOUSE_USERS,
        "keeper.xml": keeper_config(REPLICAS["clickhouse-keeper"]),
        **{_theme_key(path): content for path, content in theme.items()},
    }
    pin = _Pins(resolver)
    api_image = next(entry.image for entry in images if entry.service == "api")
    managed = {"postgres", "valkey"}
    if config.external.search is not None:
        managed.add("opensearch")

    workloads: list[dict[str, Any]] = []
    jobs: list[dict[str, Any]] = []
    waits: dict[str, list[dict[str, Any]]] = {}
    for name, service in services.items():
        if name in managed or "batch" in service.get("profiles", []):
            continue  # what the cloud runs; the on-demand loader
        one_shot = service.get("restart") == "no"
        if name in WORKER_IMAGES:
            image, service = _owned(api_image, name), {**service, "entrypoint": None}
        else:
            image = str(service["image"])
        workload: dict[str, Any] = {
            "name": name,
            "image": pin(name, image),
            "egress": "egress" in service.get("networks", []),
        }
        if (command := _cmd(service.get("entrypoint"))) is not None:
            workload["command"] = command
        if (args := _cmd(service.get("command"))) is not None:
            workload["args"] = args
        if env := translate.env(service.get("environment")):
            workload["env"] = env
        if "env_file" in service:
            workload["envFrom"] = True
        if (probe := _probe(service.get("healthcheck"))) is not None:
            workload["probe"] = probe
        if user := service.get("user"):
            uid, _, gid = str(user).partition(":")
            workload["runAs"] = {"user": int(uid), "group": int(gid or uid)}
        workload.update(_volumes(name, list(service.get("volumes", [])), config, sorted(theme)))
        if one_shot and name == "keycloak-db":
            # Run before Keycloak at every start, as compose runs it at every `up`.
            waits.setdefault("keycloak", []).append(workload)
            continue
        if one_shot:
            jobs.append(_job(workload, services, name, waits))
            continue
        workload["kind"] = "StatefulSet" if name in STATEFUL else "Deployment"
        workload["replicas"] = REPLICAS.get(name, 1)
        if name in PORTS:
            workload["ports"] = PORTS[name]
        if name in CLAIMS:
            workload["claims"] = [
                {"name": claim, "mountPath": path, "size": size}
                for claim, path, size in CLAIMS[name]
            ]
        workloads.append(workload)

    workers = {
        "name": "worker",
        "kind": "Deployment",
        "replicas": REPLICAS["worker"],
        "image": pin("worker", _owned(api_image, "worker")),
        "envFrom": True,
        # The managed Valkey is outside the cluster's network.
        "egress": True,
    }
    workloads.append(workers)
    workloads.append(_keeper(pin))
    for workload in workloads:
        _cluster_changes(workload)
        if workload["name"] in waits:
            workload["initContainers"] = waits[workload["name"]]
    if pin.unresolved and not allow_unpinned:
        raise UnpinnedImagesError(pin.unresolved)

    values = {
        "secrets": {
            "name": SECRET_NAME,
            "keys": sorted(translate.secret_keys | {"OSPREY_ARCADEDB_CLUSTER_TOKEN"}),
            "defaults": dict(sorted(translate.secret_defaults.items())),
        },
        "storage": {"className": "", "sharedClassName": "", "sharedSize": "200Gi"},
        "imagePullSecrets": [],
        "environment": environment,
        "files": files,
        "workloads": workloads,
        "jobs": jobs,
    }
    return {
        "values.yaml": _BANNER
        + yaml.safe_dump(values, sort_keys=False, default_flow_style=False, width=4096),
        "versions.lock": _render_versions_lock(
            list(pin.ran.values()),
            resolver,
            allow_unpinned=allow_unpinned,
            resolved_source_label=resolved_source_label,
        ),
    }


def _job(
    workload: dict[str, Any],
    services: dict[str, Any],
    name: str,
    waits: dict[str, list[dict[str, Any]]],
) -> dict[str, Any]:
    """A one-shot step as a Job. A service compose starts only once the step has finished waits
    for the step's mark on the volume they share."""
    dependants = [
        other
        for other, stanza in services.items()
        if (stanza.get("depends_on") or {}).get(name, {}).get("condition")
        == "service_completed_successfully"
    ]
    if dependants:
        command, args = workload.get("command"), workload.get("args")
        shared = workload.get("shared", [])
        if command != ["/bin/sh", "-c"] or not args or len(args) != 1 or len(shared) != 1:
            raise ClusterNotRenderable(f"{name}'s finish cannot be marked for {dependants}")
        mark = f"{shared[0]['mountPath']}/.ospreyflow-{name}-done"
        workload["args"] = [f"({args[0]}) && touch {mark}"]
        for dependant in dependants:
            waits.setdefault(dependant, []).append(
                {
                    "name": f"wait-for-{name}",
                    "image": workload["image"],
                    "command": ["/bin/sh", "-c"],
                    "args": [f"until [ -e {mark} ]; do sleep 5; done"],
                    "shared": shared,
                }
            )
    workload["kind"] = "Job"
    return workload


def _keeper(pin: _Pins) -> dict[str, Any]:
    """ClickHouse's coordination (05 §3b), which compose does not run: one server needs none."""
    return {
        "name": "clickhouse-keeper",
        "kind": "StatefulSet",
        "replicas": REPLICAS["clickhouse-keeper"],
        "image": pin("clickhouse-keeper", KEEPER_IMAGE),
        "command": ["/bin/sh", "-c"],
        # The id is the pod's ordinal plus one: the Keepers' Raft numbers its servers from one.
        # `$$(` is the chart's escape for a `$(` the shell reads.
        "args": ["export KEEPER_ID=$$((${HOSTNAME##*-} + 1)); exec /entrypoint.sh"],
        "egress": False,
        "ports": PORTS["clickhouse-keeper"],
        "files": [
            {"key": "keeper.xml", "mountPath": "/etc/clickhouse-keeper/keeper_config.d/raft.xml"}
        ],
        "claims": [
            {"name": claim, "mountPath": path, "size": size}
            for claim, path, size in CLAIMS["clickhouse-keeper"]
        ],
        "probe": {
            "exec": ["/bin/sh", "-c", "echo ruok | nc -w 2 127.0.0.1 9181 | grep -q imok"],
            "periodSeconds": 10,
            "timeoutSeconds": 5,
            "failureThreshold": 12,
        },
    }


def _cluster_changes(workload: dict[str, Any]) -> None:
    """What a cluster changes of a service beyond its replica count (05 §3b)."""
    name = workload["name"]
    if workload.get("kind") == "StatefulSet":
        workload.setdefault("env", []).insert(0, {"name": "POD_NAME", "field": "metadata.name"})
    if name == "arcadedb":
        env = [e for e in workload["env"] if e["name"] != "JAVA_OPTS"]
        for key in ("OSPREY_ARCADEDB_PASSWORD", "OSPREY_ARCADEDB_CLUSTER_TOKEN"):
            if all(e["name"] != key for e in env):
                env.insert(1, {"name": key, "secret": key})
        env.append({"name": "JAVA_OPTS", "value": _arcadedb_java_opts(workload["replicas"])})
        workload["env"] = env
    if name == "clickhouse":
        workload["env"].insert(
            1, {"name": "POD_ADDRESS", "value": "$(POD_NAME).clickhouse-headless"}
        )
        workload["files"] = [
            *workload.get("files", []),
            {"key": "clickhouse.xml",
             "mountPath": "/etc/clickhouse-server/config.d/replication.xml"},
            {"key": "clickhouse-users.xml",
             "mountPath": "/etc/clickhouse-server/users.d/replicated-only.xml"},
        ]  # fmt: skip
        # The adapter reads `CLICKHOUSE_PASSWORD`; the server's own config reads it too.
        if all(e["name"] != "CLICKHOUSE_PASSWORD" for e in workload["env"]):
            workload["env"].append(
                {"name": "CLICKHOUSE_PASSWORD", "secret": "OSPREY_CLICKHOUSE_PASSWORD"}
            )
    if name == "keycloak":
        workload["env"] += [
            {"name": "KC_CACHE", "value": "ispn"},
            {"name": "KC_CACHE_STACK", "value": "kubernetes"},
        ]
        workload["jgroups"] = True
    if name == "proxy":
        workload["public"] = True
