"""`profile: cluster`: the values for the chart `deploy/helm/ospreyflow` (`05_DEPLOYMENT.md` §3b,
ADR-114 decision 9, Amendment 12).

**Translated, not written again.** Every workload is the compose stanza `harness.render` writes for
Lite and Small (`compose_services`), translated: its image pinned by digest, its environment, its
command, its health check, its files and its volumes. A cluster then changes only what a cluster
changes — the replica counts, the stores' clustering (ArcadeDB's Raft, ClickHouse's replicas and
Keepers, Keycloak's caches), the job workers, and what the cloud runs instead of a container. So a
service cannot be one thing on a laptop and another on Kubernetes.

The chart is generic: it turns `workloads` into Deployments, StatefulSets, Jobs, Services and
NetworkPolicies, `environment` into the ConfigMap every owned service reads (Lite's
`deployment.env`), and `files` into the ConfigMap the configuration files are mounted from. Secrets
are never here: every workload reads them from one Kubernetes Secret the install creates, and
`secrets.keys` lists every key a workload names.

    compose `${VAR}` in a value     → read from the Secret, or from `environment` if rendered there
    compose `entrypoint` / `command` → `command` / `args`
    compose healthcheck              → readiness probe
    `./<file>` mount                 → the files ConfigMap
    a named volume                   → the shared volume (ReadWriteMany) on a Deployment or Job, a
                                       claim of its own on a StatefulSet
    a host folder (ingest, tiles)    → the shared volume
    a one-shot step                  → a Job (it reaches out; the server it feeds does not), or an
                                       init container of the service that needs it first
"""

