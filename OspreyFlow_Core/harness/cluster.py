_REF = re.compile(r"\$\{(?P<name>[A-Za-z_][A-Za-z0-9_]*)(?P<rest>[^}]*)\}")


class ClusterNotRenderable(ValueError):
    """The configuration names something a cluster cannot run; the message says what."""


def _seconds(value: object) -> int:
    text = str(value)
    if text.endswith("ms"):
        return max(1, int(text[:-2]) // 1000)
    if text.endswith("m"):
        return int(text[:-1]) * 60
    return int(text.rstrip("s"))


def _no_compose_escapes(text: str) -> str:
    """Compose's `$$` is one `$`; a `$(` the chart would read as a variable is escaped for it."""
    return text.replace("$$", "$").replace("$(", "$$(")


class _Translator:
    def __init__(self, environment: dict[str, str]) -> None:
        self.environment = environment
        self.secret_keys: set[str] = set()
        self.secret_defaults: dict[str, str] = {}

    def _source(self, name: str, rest: str) -> dict[str, str]:
        if name in self.environment:
            return {"name": name, "config": name}
        self.secret_keys.add(name)
        if rest.startswith(":-") or rest.startswith("-"):
            self.secret_defaults.setdefault(name, rest.split("-", 1)[1])
        return {"name": name, "secret": name}

    def env(self, given: object) -> list[dict[str, str]]:
        """Compose's environment as the chart's: a whole `${VAR}` read from where it lives; one
        inside a longer value defined first, then named as `$(VAR)`."""
        if not isinstance(given, dict):
            return []
        first: list[dict[str, str]] = []
        entries: list[dict[str, str]] = []
        for name, raw in given.items():
            value = str(raw)
            refs = list(_REF.finditer(value))
            if not refs:
                entries.append({"name": name, "value": value.replace("$$", "$")})
            elif len(refs) == 1 and refs[0].span() == (0, len(value)):
                entries.append({**self._source(refs[0]["name"], refs[0]["rest"]), "name": name})
            else:
                for ref in refs:
                    if all(e["name"] != ref["name"] for e in first):
                        first.append(self._source(ref["name"], ref["rest"]))
                entries.append({"name": name, "value": _REF.sub(r"$(\g<name>)", value)})
        return first + entries


def _probe(check: object) -> dict[str, Any] | None:
    if not isinstance(check, dict):
        return None
    test = list(check["test"])
    if any("${" in str(part) for part in test):
        raise ClusterNotRenderable(f"a health check reads a compose variable: {test!r}")
    command = test[1:] if test[0] == "CMD" else ["/bin/sh", "-c", test[1]]
    probe: dict[str, Any] = {
        "exec": command,
        "periodSeconds": _seconds(check.get("interval", "10s")),
        "timeoutSeconds": _seconds(check.get("timeout", "5s")),
        "failureThreshold": int(check.get("retries", 3)),
    }
    if "start_period" in check:
        probe["initialDelaySeconds"] = _seconds(check["start_period"])
    return probe


def _theme_key(path: str) -> str:
    return "theme--" + path.replace("/", "--")


def _host_folders(config: OspreyConfig) -> list[tuple[str, str]]:
    storage = config.components.storage
    return sorted(
        [(str(storage.ingest), "ingest"), (str(storage.tiles), "tiles")],
        key=lambda pair: -len(pair[0]),
    )


def _volumes(
    service: str, mounts: list[str], config: OspreyConfig, theme_files: list[str]
) -> dict[str, Any]:
    stateful = service in STATEFUL
    out: dict[str, Any] = {"files": [], "fileDirs": [], "shared": [], "scratch": []}
    for mount in mounts:
        source, target, *mode = mount.split(":")
        read_only = mode == ["ro"]
        if source == "./state":
            # The update notice is written on a Lite host by `update --check`; a cluster's is not.
            out["scratch"].append({"mountPath": target})
        elif source.startswith("./keycloak-theme/"):
            out["fileDirs"].append(
                {"mountPath": target,
                 "items": [{"key": _theme_key(path), "path": path} for path in theme_files]}
            )  # fmt: skip
        elif source.startswith("./"):
            out["files"].append({"key": source[2:], "mountPath": target})
        elif source.startswith("/"):
            for folder, shared in _host_folders(config):
                if source == folder or source.startswith(folder + "/"):
                    sub = shared + source[len(folder) :]
                    out["shared"].append(
                        {"subPath": sub, "mountPath": target, "readOnly": read_only}
                    )
                    break
            else:
                raise ClusterNotRenderable(f"{service} mounts a host folder {source!r}")
        elif stateful:
            continue  # its claims (CLAIMS) hold what its named volume held
        elif source in SHARED_VOLUMES:
            out["shared"].append(
                {"subPath": SHARED_VOLUMES[source], "mountPath": target, "readOnly": read_only}
            )
        else:
            raise ClusterNotRenderable(
                f"{service} mounts a volume {source!r} the chart has no place for"
            )
    return {key: value for key, value in out.items() if value}


def _cmd(value: object) -> list[str] | None:
    if value is None:
        return None
    parts = [value] if isinstance(value, str) else list(value)  # type: ignore[call-overload]
    return [_no_compose_escapes(str(part)) for part in parts]


class _Pins:
    """Each image pinned by the digest its registry holds, and remembered for the lock."""

    def __init__(self, resolver: DigestResolver) -> None:
        self.resolver = resolver
        self.unresolved: list[str] = []
        self.ran: dict[str, ServiceImage] = {}

    def __call__(self, service: str, image: str) -> str:
        self.ran.setdefault(service, ServiceImage(service, image))
        digest = self.resolver(image)
        if digest is None:
            self.unresolved.append(image)
            return image
        return f"{image}@{digest}"


def _owned(api_image: str, service: str) -> str:
    repository, _, tag = api_image.rpartition(":")
    return f"{repository.rpartition('/')[0]}/{service}:{tag}"


def _arcadedb_java_opts(replicas: int) -> str:
    servers = ",".join(f"arcadedb-{n}.arcadedb-headless:2434:2480" for n in range(replicas))
