def _q(text: str) -> str:
    return json.dumps(text)


def _hcl(items: list[Any], indent: int = 0) -> str:
    """Attributes `(name, expression)`, maps `(name, {key: expression})` and blocks `(header,
    items)`, with `fmt`'s alignment: the `=` of consecutive one-line attributes lined up."""
    pad = "  " * indent
    out: list[str] = []
    run: list[Attr] = []

    def flush() -> None:
        width = max((len(k) for k, _ in run), default=0)
        out.extend(f"{pad}{k.ljust(width)} = {v}" for k, v in run)
        run.clear()

    for header, body in items:
        if isinstance(body, list):
            flush()
            if out and out[-1] != "":
                out.append("")
            out += [f"{pad}{header} {{", _hcl(body, indent + 1), f"{pad}}}", ""]
        elif isinstance(body, dict):
            flush()
            width = max(len(k) for k in body)
            inner = [f"{pad}  {k.ljust(width)} = {v}" for k, v in body.items()]
            out += [f"{pad}{header} = {{", *inner, f"{pad}}}"]
        else:
            run.append((header, body))
    flush()
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out)


def _file(intro: str, blocks: list[Block]) -> str:
    comment = "".join(f"# {line}\n" if line else "#\n" for line in intro.splitlines())
    return comment + "\n" + "\n\n".join(_hcl([b]) for b in blocks) + "\n"


def _secret(name: str, data: dict[str, str]) -> Block:
    return (
        f'resource "kubernetes_secret" {_q(re.sub(r"[^a-z0-9]", "_", name))}',
        [
            ("metadata", [("name", _q(name)), ("namespace", "var.namespace")]),
            ("data", data),
        ],
    )


def ecr_repositories(values: dict[str, Any], registry: str) -> list[str]:
    paths: set[str] = set()
    for pod in [*values["workloads"], *values["jobs"]]:
        for container in [pod, *pod.get("initContainers", [])]:
            image = container["image"].removeprefix(registry + "/")
            paths.add(image.split("@")[0].rsplit(":", 1)[0])
    return sorted(paths)


