"""The Admin area's Demo packs tab (`06_DECISIONS.md` ADR-114 Amendment 5, the owner's "Show and
explain"): each shipped pack — what it shows, its licence and credit — whether it is loaded, and the
exact command that adds it on the host. The Conduit never runs it: it has no control of Docker.

What a mistake would do, and the case that catches it:
- the tab open to anyone — `test_the_packs_are_refused_without_administer_system`;
- an internal demo offered, or a pack's licence or credit dropped —
  `test_every_shipped_pack_is_listed_with_its_licence_and_credit_and_no_internal_one`;
- a command that would not run (PaySim without its file) — `test_each_pack_says_the_command_that_adds_it`;
- a case the administrator cannot open disclosed through "loaded" —
  `test_a_pack_is_loaded_only_in_a_case_you_can_open`.
"""

from __future__ import annotations

from typing import Any

import pytest
from fastapi.testclient import TestClient
from services.api.app import app, get_audit, get_investigations, get_principal

from schemas.domain import Principal

ADMIN = Principal(id="admin-1", clearance="OFFICIAL", org_unit="verify", roles=["osprey-admin"])
ANALYST = Principal(id="analyst-1", clearance="OFFICIAL", org_unit="verify", roles=["analyst"])


class _Case:
    def __init__(self, case_id: str, name: str) -> None:
        self.id, self.name = case_id, name


class _Investigations:
    def __init__(self, visible: list[_Case]) -> None:
        self.visible = visible

    async def list_for(self, principal: Principal) -> list[tuple[_Case, str]]:
        return [(case, "author") for case in self.visible]


class _Audit:
    def __init__(self) -> None:
        self.records: list[dict[str, Any]] = []

    async def record(self, **kwargs: Any) -> None:
        self.records.append(kwargs)


@pytest.fixture
def client() -> Any:
    audit = _Audit()
    investigations = _Investigations([_Case("c-ledger", "Operation Ledger (synthetic demo)")])
    app.dependency_overrides[get_audit] = lambda: audit
    app.dependency_overrides[get_investigations] = lambda: investigations
    test_client = TestClient(app)
    test_client.audit = audit  # type: ignore[attr-defined]
    yield test_client
    app.dependency_overrides.clear()


def _packs(client: Any, who: Principal = ADMIN) -> Any:
    app.dependency_overrides[get_principal] = lambda: who
    return client.get("/v1/admin/demo-packs")


def test_the_packs_are_refused_without_administer_system(client: Any) -> None:
    assert _packs(client, ANALYST).status_code == 403
    assert client.audit.records == []


def test_every_shipped_pack_is_listed_with_its_licence_and_credit_and_no_internal_one(client: Any) -> None:
    response = _packs(client)
    assert response.status_code == 200, response.text
    listed = {p["id"]: p for p in response.json()}
    assert set(listed) == {"hmp", "fixture-corp", "operation-ledger", "paysim", "enron"}
    # ADR-114 Amendment 23 point 4: the real one says so wherever it is listed; no other does.
    assert {pack_id for pack_id, p in listed.items() if p["real_data"]} == {"enron"}
    assert listed["paysim"]["licence"] == "CC-BY-SA-4.0" and "Lopez-Rojas" in listed["paysim"]["attribution"]
    assert listed["hmp"]["licence"].startswith("Generated by OspreyFlow")
    assert [r["action"] for r in client.audit.records] == ["list_demo_packs"]


def test_each_pack_says_the_command_that_adds_it(client: Any) -> None:
    listed = {p["id"]: p for p in _packs(client).json()}
    assert listed["hmp"]["command"] == "ospreyflow demo add hmp"
    assert listed["paysim"]["command"] == (
        "ospreyflow demo add paysim --file <the downloaded PS_20174392719_1491204439457_log.csv>"
    )
    assert listed["paysim"]["source_page"] == "https://www.kaggle.com/datasets/ealaxi/paysim1"
    assert listed["paysim"]["size_bytes"] == 493534783


def test_a_pack_is_loaded_only_in_a_case_you_can_open(client: Any) -> None:
    listed = {p["id"]: p for p in _packs(client).json()}
    assert listed["operation-ledger"]["loaded_case_id"] == "c-ledger"
    assert listed["hmp"]["loaded_case_id"] is None, "absent, or in a case this administrator cannot open"
