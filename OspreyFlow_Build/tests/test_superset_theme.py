"""Superset's light and dark themes come from `tokens.css` (`06_DECISIONS.md` ADR-111 Amendment 4).

`deploy/superset/osprey_theme.json` is generated by `scripts/superset_theme.py` and committed, because
the Superset image is built from `deploy/superset/` alone and cannot read the Glass's tokens.

What a mistake would do, and the case that catches it:
- the committed file drifting from the tokens (a token changed, the theme not regenerated) —
  `test_the_committed_theme_is_what_the_tokens_make`;
- a colour typed into the theme by hand — `test_every_colour_in_the_theme_is_a_token`;
- the dark theme built from the light set, or the reverse — `test_each_theme_comes_from_its_own_set`;
- a chart drawn in brass, or in anything but the both-modes chart set —
  `test_both_themes_draw_charts_in_the_both_modes_set`;
- a chart colour that fades into either panel (the owner's ruling of 12 October 2026: one set that
  reads in both modes, at least 3:1 against each) — `test_every_chart_colour_holds_three_to_one_on_both_panels`.
"""

from __future__ import annotations

import json
import re
from typing import Any

from scripts import superset_theme
from tools.layout import CORE

THEME_FILE = CORE / "deploy" / "superset" / "osprey_theme.json"
TOKENS = (CORE / "apps" / "workspace" / "src" / "design" / "tokens.css").read_text(encoding="utf-8")
CHANNELS = ("azure", "ochre", "jade", "violet", "cyan", "rose", "moss", "indigo", "plum")


def _colours(value: Any) -> set[str]:
    return {c.lower() for c in re.findall(r"#[0-9a-fA-F]{6}\b", json.dumps(value))}


def test_the_committed_theme_is_what_the_tokens_make() -> None:
    committed = THEME_FILE.read_text(encoding="utf-8")
    assert committed == superset_theme.render(TOKENS), (
        "osprey_theme.json is out of date: run `python -m scripts.superset_theme`"
    )


def test_every_colour_in_the_theme_is_a_token() -> None:
    defined = {c.lower() for c in re.findall(r"#[0-9a-fA-F]{6}\b", TOKENS)}
    themes = json.loads(superset_theme.render(TOKENS))
    assert _colours(themes) <= defined, _colours(themes) - defined


def test_each_theme_comes_from_its_own_set() -> None:
    dark, light = superset_theme.token_sets(TOKENS)
    themes = json.loads(superset_theme.render(TOKENS))
    assert themes["dark"]["algorithm"] == "dark" and themes["default"]["algorithm"] == "default"
    assert themes["dark"]["token"]["colorPrimary"] == dark["brass"] == "#c08a34"
    assert themes["default"]["token"]["colorPrimary"] == light["brass"] == "#8a6318"
    assert themes["dark"]["token"]["colorBgLayout"] == dark["n1"]
    assert themes["default"]["token"]["colorBgLayout"] == light["n1"]
    assert themes["dark"]["token"]["colorText"] == dark["n11"]
    assert themes["default"]["token"]["colorText"] == light["n11"]
    assert themes["dark"]["token"]["fontFamily"].startswith("'Atkinson Hyperlegible Next'")


def test_both_themes_draw_charts_in_the_both_modes_set() -> None:
    dark, light = superset_theme.token_sets(TOKENS)
    themes = json.loads(superset_theme.render(TOKENS))
    chart = [dark[f"chart-{name}"] for name in CHANNELS]
    assert chart == [light[f"chart-{name}"] for name in CHANNELS], "one set, not tuned per theme"
    for mode in ("dark", "default"):
        assert themes[mode]["echartsOptionsOverrides"]["color"] == chart, mode
    assert themes["categorical"]["colors"] == chart
    assert not {dark["brass"], light["brass"], dark["brass-hover"], light["brass-hover"]} & set(chart)


def _luminance(colour: str) -> float:
    def linear(channel: int) -> float:
        c = channel / 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (int(colour[i : i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b)


def _contrast(a: str, b: str) -> float:
    high, low = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def test_every_chart_colour_holds_three_to_one_on_both_panels() -> None:
    dark, light = superset_theme.token_sets(TOKENS)
    for name in CHANNELS:
        colour = dark[f"chart-{name}"]
        for panel in (dark["surface-panel"], light["surface-panel"]):
            assert _contrast(colour, panel) >= 3.0, (name, colour, panel, _contrast(colour, panel))
